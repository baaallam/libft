#include "libft.h"

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	len;

	len = ft_strlen(src);
	i = 0;
	if (size == 0)
		return (len);
	while (size - 1 > 0 && src[i] != 0)
	{
		dst[i] = src[i];
		i++;
		size--;
	}
	dst[i] = 0;
	return (len);
}
